/// Canonical Typed Intermediate Representation for Infrastructure Architecture
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Architecture {
    pub metadata: ArchitectureMetadata,
    pub provider_target: ProviderTarget,
    pub workloads: Vec<WorkloadDefinition>,
    pub service_dependencies: Vec<ServiceDependency>,
    pub availability: AvailabilityRequirements,
    pub security: SecurityRequirements,
    pub failure_domains: Vec<String>,
    pub scaling_policies: Vec<ScalingPolicy>,
    pub cost_constraints: CostConstraints,
}

impl Default for Architecture {
    fn default() -> Self {
        Self {
            metadata: ArchitectureMetadata::default(),
            provider_target: ProviderTarget::LocalDocker,
            workloads: Vec::new(),
            service_dependencies: Vec::new(),
            availability: AvailabilityRequirements::default(),
            security: SecurityRequirements::default(),
            failure_domains: vec!["default-zone".to_string()],
            scaling_policies: Vec::new(),
            cost_constraints: CostConstraints::default(),
        }
    }
}

impl Architecture {
    pub fn new(name: impl Into<String>, provider: ProviderTarget) -> Self {
        let meta = ArchitectureMetadata {
            name: name.into(),
            ..Default::default()
        };
        Self {
            metadata: meta,
            provider_target: provider,
            ..Default::default()
        }
    }

    /// Compute deterministic cryptographic hash of the architecture specification
    pub fn canonical_hash(&self) -> String {
        StateHasher::hash_json(self)
    }

    /// Convert into the SMT solver's Intent structure
    pub fn to_intent(&self) -> Intent {
        let mut solver_workloads = Vec::new();
        for w in &self.workloads {
            let mut constraints = vec![
                Constraint::CpuCores(w.compute.cpu_cores),
                Constraint::RamMb(w.compute.ram_mb),
            ];
            if w.compute.vram_mb > 0 {
                constraints.push(Constraint::VramMb(w.compute.vram_mb));
            }
            if w.compute.gpu_count > 0 {
                constraints.push(Constraint::GpuCount(w.compute.gpu_count));
            }
            if w.network.required_bandwidth_gbps > 0 {
                constraints.push(Constraint::NetworkGbps(w.network.required_bandwidth_gbps));
            }

            solver_workloads.push(Workload {
                id: w.id,
                name: w.name.clone(),
                kind: w.kind.clone(),
                containers: vec![w.container_image.clone()],
                constraints,
            });
        }

        Intent {
            intent_id: self.metadata.id,
            workloads: solver_workloads,
        }
    }

    /// Compute typed diff between this architecture (e.g. desired) and another (e.g. observed)
    pub fn diff(&self, other: &Architecture) -> ArchitectureDiff {
        let mut workload_additions = Vec::new();
        let mut workload_removals = Vec::new();
        let mut workload_modifications = Vec::new();

        let this_map: HashMap<&str, &WorkloadDefinition> = self
            .workloads
            .iter()
            .map(|w| (w.name.as_str(), w))
            .collect();
        let other_map: HashMap<&str, &WorkloadDefinition> = other
            .workloads
            .iter()
            .map(|w| (w.name.as_str(), w))
            .collect();

        for (name, w) in &this_map {
            if let Some(other_w) = other_map.get(name) {
                if *w != *other_w {
                    workload_modifications.push(((*w).clone(), (**other_w).clone()));
                }
            } else {
                workload_removals.push((*w).clone());
            }
        }

        for (name, other_w) in &other_map {
            if !this_map.contains_key(name) {
                workload_additions.push((*other_w).clone());
            }
        }

        ArchitectureDiff {
            provider_changed: self.provider_target != other.provider_target,
            workload_additions,
            workload_removals,
            workload_modifications,
            hash_matches: self.canonical_hash() == other.canonical_hash(),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ArchitectureDiff {
    pub provider_changed: bool,
    pub workload_additions: Vec<WorkloadDefinition>,
    pub workload_removals: Vec<WorkloadDefinition>,
    pub workload_modifications: Vec<(WorkloadDefinition, WorkloadDefinition)>,
    pub hash_matches: bool,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_canonical_architecture_ir_creation_and_hash() {
        let mut arch = Architecture::new("demo-service", ProviderTarget::AWS);
        arch.workloads.push(WorkloadDefinition {
            id: Uuid::new_v4(),
            name: "web-api".to_string(),
            kind: WorkloadKind::NodePostgresApi,
            container_image: "node:18-alpine".to_string(),
            entrypoint: Some("npm start".to_string()),
            ports: vec![PortDefinition {
                container_port: 3000,
                host_port: Some(80),
                protocol: "HTTP".to_string(),
            }],
            secrets: vec![SecretReference {
                env_var_name: "DATABASE_URL".to_string(),
                vault_key: "DB_SECRET".to_string(),
                optional: false,
            }],
            compute: ComputeRequirements {
                cpu_cores: 2,
                ram_mb: 2048,
                gpu_count: 0,
                vram_mb: 0,
                gpu_model_preference: None,
            },
            storage: StorageRequirements::default(),
            network: NetworkRequirements::default(),
            replicas: ReplicaPolicy {
                min_replicas: 2,
                max_replicas: 5,
                desired_replicas: 2,
            },
            placement: PlacementConstraints::default(),
        });

        let hash1 = arch.canonical_hash();
        let hash2 = arch.canonical_hash();
        assert_eq!(hash1, hash2, "Canonical hash must be deterministic");
        assert_eq!(hash1.len(), 64, "SHA-256 hash must be 64 hex chars");

        let intent = arch.to_intent();
        assert_eq!(intent.workloads.len(), 1);
        assert_eq!(intent.workloads[0].name, "web-api");
    }

    #[test]
    fn test_architecture_diffing() {
        let arch1 = Architecture::new("test", ProviderTarget::LocalDocker);
        let mut arch2 = arch1.clone();
        arch2.provider_target = ProviderTarget::Kubernetes;

        let diff = arch1.diff(&arch2);
        assert!(diff.provider_changed);
        assert!(!diff.hash_matches);
    }
}
