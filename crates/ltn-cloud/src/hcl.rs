//! OpenTofu module for one cloud target: a VM with Docker and SSH.

use anyhow::{bail, Result};
use std::net::Ipv4Addr;

pub const DEFAULT_APP_PORTS: &[u16] = &[80, 443, 8080];
pub const DEFAULT_ROOT_VOLUME_GB: u32 = 20;
pub const AL2023_SSM_PARAMETER: &str = "/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64";

#[derive(Debug, Clone)]
pub struct ModuleParams {
    /// Target name: lowercase letters, digits and `-`.
    pub target_name: String,
    /// Short random suffix that makes AWS-side names unique per target.
    pub unique_suffix: String,
    pub region: String,
    pub instance_type: String,
    /// OpenSSH public key line (e.g. `ssh-ed25519 AAAA... comment`).
    pub public_key: String,
    /// CIDR allowed to reach port 22. Must be a single host (`/32`) or a narrow range, never 0.0.0.0/0.
    pub ssh_cidr: String,
    pub app_ports: Vec<u16>,
    pub root_volume_gb: u32,
}

pub fn validate_name(name: &str) -> Result<()> {
    let ok = !name.is_empty()
        && name.len() <= 40
        && name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
        && !name.starts_with('-')
        && !name.ends_with('-');
    if !ok {
        bail!("target name `{name}` is invalid: use 1-40 lowercase letters, digits or `-` (not at the ends)");
    }
    Ok(())
}

/// Accepts `a.b.c.d/n` with n >= 8 (rejects 0.0.0.0/0 and other world-open ranges).
pub fn validate_ssh_cidr(cidr: &str) -> Result<()> {
    let (ip, len) = cidr.split_once('/').unwrap_or((cidr, ""));
    let ip_ok = ip.parse::<Ipv4Addr>().is_ok();
    let len_ok = len.parse::<u8>().map_or(false, |n| (8..=32).contains(&n));
    if !ip_ok || !len_ok {
        bail!("SSH CIDR `{cidr}` is not allowed: give an IPv4 CIDR with prefix /8../32 (normally your public IP /32), never 0.0.0.0/0");
    }
    Ok(())
}

/// Escapes a value for an HCL double-quoted string (including template sequences).
pub fn hcl_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '$' if chars.peek() == Some(&'{') => out.push_str("$$"),
            '%' if chars.peek() == Some(&'{') => out.push_str("%%"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Resource prefix used for AWS-side names, e.g. `ltn-web-1a2b3c4d`.
pub fn aws_name(p: &ModuleParams) -> String {
    format!("ltn-{}-{}", p.target_name, p.unique_suffix)
}

/// Renders `main.tf` for one target. Values that differ per apply (region,
/// root volume size) are variables whose defaults are the chosen values.
pub fn render_module(p: &ModuleParams) -> Result<String> {
    validate_name(&p.target_name)?;
    validate_ssh_cidr(&p.ssh_cidr)?;
    if p.unique_suffix.is_empty() || !p.unique_suffix.chars().all(|c| c.is_ascii_alphanumeric()) {
        bail!("unique suffix must be non-empty alphanumeric");
    }
    if p.instance_type.is_empty() || !p.instance_type.chars().all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-') {
        bail!("instance type `{}` is invalid", p.instance_type);
    }
    if p.region.is_empty() || !p.region.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        bail!("region `{}` is invalid", p.region);
    }
    if !p.public_key.starts_with("ssh-") || p.public_key.contains('\n') {
        bail!("public key must be one OpenSSH public key line");
    }
    if p.app_ports.contains(&22) {
        bail!("port 22 cannot be an app port: SSH is only opened to the operator CIDR");
    }
    if p.app_ports.contains(&0) {
        bail!("app port 0 is invalid");
    }
    if !(8..=16384).contains(&p.root_volume_gb) {
        bail!("root volume size {} GB is outside 8..16384", p.root_volume_gb);
    }
    let mut ports = p.app_ports.clone();
    ports.sort_unstable();
    ports.dedup();

    let name = aws_name(p);
    let target = hcl_str(&p.target_name);
    let app_ingress: String = ports
        .iter()
        .map(|port| {
            format!(
                r#"
  ingress {{
    description = "app port {port}"
    from_port   = {port}
    to_port     = {port}
    protocol    = "tcp"
    cidr_blocks = ["0.0.0.0/0"]
  }}
"#
            )
        })
        .collect();

    Ok(format!(
        r#"# Generated by ltn-cloud for target {target_name}. Do not edit by hand:
# ltn regenerates it and destroys with `tofu destroy` in this directory.

terraform {{
  required_version = ">= 1.6.0"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

variable "region" {{
  type    = string
  default = {region}
}}

variable "root_volume_gb" {{
  type    = number
  default = {root}
}}

provider "aws" {{
  region = var.region
  default_tags {{
    tags = local.tags
  }}
}}

locals {{
  tags = {{
    "ltn:target"  = {target}
    "ltn:managed" = "true"
  }}
}}

data "aws_ssm_parameter" "al2023" {{
  name = {ssm}
}}

resource "aws_key_pair" "target" {{
  key_name   = {name_q}
  public_key = {pubkey}
}}

resource "aws_security_group" "target" {{
  name        = {name_q}
  description = {sg_desc}

  ingress {{
    description = "SSH from the operator only"
    from_port   = 22
    to_port     = 22
    protocol    = "tcp"
    cidr_blocks = [{ssh_cidr}]
  }}
{app_ingress}
  egress {{
    from_port   = 0
    to_port     = 0
    protocol    = "-1"
    cidr_blocks = ["0.0.0.0/0"]
  }}
}}

resource "aws_instance" "target" {{
  ami                         = data.aws_ssm_parameter.al2023.insecure_value
  instance_type               = {itype}
  key_name                    = aws_key_pair.target.key_name
  vpc_security_group_ids      = [aws_security_group.target.id]
  associate_public_ip_address = true
  user_data_replace_on_change = true

  user_data = <<-EOT
    #!/bin/bash
    set -euxo pipefail
    dnf install -y docker
    systemctl enable --now docker
    usermod -aG docker ec2-user
  EOT

  metadata_options {{
    http_tokens = "required"
  }}

  root_block_device {{
    volume_size = var.root_volume_gb
    volume_type = "gp3"
    encrypted   = true
  }}

  tags = {{
    Name = {name_q}
  }}
}}

output "instance_id" {{
  value = aws_instance.target.id
}}

output "public_ip" {{
  value = aws_instance.target.public_ip
}}
"#,
        target_name = p.target_name,
        region = hcl_str(&p.region),
        root = p.root_volume_gb,
        ssm = hcl_str(AL2023_SSM_PARAMETER),
        name_q = hcl_str(&name),
        pubkey = hcl_str(p.public_key.trim()),
        sg_desc = hcl_str(&format!("ltn target {}: SSH from operator, app ports", p.target_name)),
        ssh_cidr = hcl_str(&p.ssh_cidr),
        itype = hcl_str(&p.instance_type),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    pub(crate) fn params() -> ModuleParams {
        ModuleParams {
            target_name: "web-1".into(),
            unique_suffix: "a1b2c3d4".into(),
            region: "us-east-1".into(),
            instance_type: "t3.small".into(),
            public_key: "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIExampleKeyMaterialOnly ltn-web-1".into(),
            ssh_cidr: "203.0.113.7/32".into(),
            app_ports: DEFAULT_APP_PORTS.to_vec(),
            root_volume_gb: DEFAULT_ROOT_VOLUME_GB,
        }
    }

    /// The text of the `ingress` block that opens port 22.
    fn ssh_block(hcl: &str) -> String {
        let blocks: Vec<&str> = hcl.split("ingress {").skip(1).collect();
        let b = blocks.iter().find(|b| b.contains("from_port   = 22\n")).expect("ssh block");
        b.split('}').next().unwrap().to_string()
    }

    #[test]
    fn module_has_expected_resources() {
        let hcl = render_module(&params()).unwrap();
        for needle in [
            "source  = \"hashicorp/aws\"",
            "version = \"~> 5.0\"",
            "variable \"region\"",
            "variable \"root_volume_gb\"",
            "region = var.region",
            "resource \"aws_key_pair\" \"target\"",
            "resource \"aws_security_group\" \"target\"",
            "resource \"aws_instance\" \"target\"",
            "data \"aws_ssm_parameter\" \"al2023\"",
            AL2023_SSM_PARAMETER,
            "instance_type               = \"t3.small\"",
            "volume_size = var.root_volume_gb",
            "dnf install -y docker",
            "systemctl enable --now docker",
            "usermod -aG docker ec2-user",
            "\"ltn:target\"  = \"web-1\"",
            "output \"instance_id\"",
            "output \"public_ip\"",
            "\"ltn-web-1-a1b2c3d4\"",
            "from_port   = 80",
            "from_port   = 443",
            "from_port   = 8080",
        ] {
            assert!(hcl.contains(needle), "missing `{needle}` in\n{hcl}");
        }
        let ssh = ssh_block(&hcl);
        assert!(ssh.contains("203.0.113.7/32"), "{ssh}");
        assert!(!ssh.contains("0.0.0.0/0"), "{ssh}");
    }

    #[test]
    fn world_open_ssh_and_bad_inputs_are_refused() {
        for bad in ["0.0.0.0/0", "10.0.0.0/4", "203.0.113.7", "::/0", "x/32"] {
            let mut p = params();
            p.ssh_cidr = bad.into();
            assert!(render_module(&p).is_err(), "{bad} accepted");
        }
        let mut p = params();
        p.app_ports = vec![22, 80];
        assert!(render_module(&p).is_err());
        let mut p = params();
        p.target_name = "Bad_Name".into();
        assert!(render_module(&p).is_err());
        let mut p = params();
        p.public_key = "not a key".into();
        assert!(render_module(&p).is_err());
    }

    #[test]
    fn names_are_unique_per_target_and_strings_escaped() {
        let a = render_module(&params()).unwrap();
        let mut p = params();
        p.target_name = "api".into();
        p.unique_suffix = "ffff0000".into();
        let b = render_module(&p).unwrap();
        assert!(b.contains("\"ltn-api-ffff0000\"") && !b.contains("ltn-web-1-a1b2c3d4"));
        assert_ne!(a, b);
        assert_eq!(hcl_str("a\"b${x}%{y}\\"), "\"a\\\"b$${x}%%{y}\\\\\"");
    }
}
